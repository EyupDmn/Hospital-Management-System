    public void loadBolum() {
        Connection connection = null;
        DbHelper helper = new DbHelper();
        Statement statement = null;
        ResultSet resultSet;
        ArrayList<String> bolumler = null;
        try {
            connection = helper.getConnection();
            statement = connection.createStatement();
            resultSet = statement.executeQuery("select * from bolumler");
            bolumler = new ArrayList<String>();
            while (resultSet.next()) {
                bolumler.add((resultSet.getString("bolum_adi")));
            }
            for (String bolum : bolumler) {
                cmbBolum.addItem(bolum);
            }
        } catch (SQLException exception) {
            helper.showErrorMessage(exception);
        } finally {
            try {
                statement.close();
                connection.close();
            } catch (SQLException ex) {
            }
        }
    }
    
    public void loadDoktor() {
        cmbDoktor.removeAllItems();
        bolumId = doctor.bolumId((String) cmbBolum.getSelectedItem());
        ArrayList<String> doctorlar;
        try {
            doctorlar = getDoctors();
            for (String str : doctorlar) {
                cmbDoktor.addItem(str);
            }
        } catch (SQLException ex) {
            System.out.println(ex.getErrorCode());
        }
    }
    
    public ArrayList<String> getDoctors() throws SQLException {
        Connection connection = null;
        DbHelper helper = new DbHelper();
        Statement statement = null;
        ResultSet resultSet;
        ArrayList<String> doctors = null;
        try {
            connection = helper.getConnection();
            statement = connection.createStatement();
            resultSet = statement.executeQuery("select * from doktorlar where bolum_id = " + bolumId);
            doctors = new ArrayList<String>();
            while (resultSet.next()) {
                String isim = resultSet.getString("ad") + " " + resultSet.getString("soyad");
                doctors.add(isim);
            }
        } catch (SQLException e) {
            helper.showErrorMessage(e);
        } finally {
            statement.close();
            connection.close();
        }
        return doctors;
    }

    public String control() {
        String sql = "select * from v_randevular where 1 = 1";
        if (!ftxtHastaTC.getText().equals("           ")) {
            sql += " and hasta_id = " + appointment.hastaId(ftxtHastaTC.getText());
        }
        if (!cmbBolum.getSelectedItem().equals("Hepsi")) {
            sql += " and bolum_id = " + doctor.bolumId((String) cmbBolum.getSelectedItem());
        }
        if (!cmbDoktor.getSelectedItem().equals("Hepsi")) {
            sql += " and doktor_adsoyad = '" + (String) cmbDoktor.getSelectedItem()+"'";
        }
        if (!ftxtBaslangicTarihi.getText().equals("  -  -    ")) {
            sql += " and tarih >= '" + login.formattedDate(ftxtBaslangicTarihi.getText())+"'";
        }
        if (!ftxtBitisTarihi.getText().equals("  -  -    ")) {
            sql += " and tarih <= '" + login.formattedDate(ftxtBitisTarihi.getText())+"'";
        }
        return sql;
    }

