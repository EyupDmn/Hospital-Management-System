    private void btnListeleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnListeleActionPerformed
        // TODO add your handling code here:
        Connection connection = null;
        DbHelper helper = new DbHelper();
        PreparedStatement statement = null;
        ResultSet resultSet;
        model.setRowCount(0);
        try {
            connection = helper.getConnection();
            statement = connection.prepareStatement(control());
            resultSet = statement.executeQuery();
            while (resultSet.next()) {
                Object[] row = {resultSet.getString("doktor_adsoyad"), resultSet.getString("hasta_adsoyad"), resultSet.getString("bolum_adi"), login.getirFormattedDate(resultSet.getString("tarih"))};
                model.addRow(row);
            }
        } catch (SQLException e) {
            helper.showErrorMessage(e);
        } finally {
            try {
                statement.close();
                connection.close();
            } catch (SQLException ex) {
            }
        }
        ftxtBaslangicTarihi.setText("");
        ftxtBitisTarihi.setText("");
    }//GEN-LAST:event_btnListeleActionPerformed

