public class Department {
    private int id;
    String bolum;

    public Department(int id, String bolum) {
        this.id = id;
        this.bolum = bolum;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getBolum() {
        return bolum;
    }

    public void setBolum(String bolum) {
        this.bolum = bolum;
    }
    
    
}
